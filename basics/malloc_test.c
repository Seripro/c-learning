#include <stdio.h>
#include <stdlib.h> // ★ malloc と free を使うための新しい設計図だ

int main(void) {
    // 1. メモリの確保（広大な倉庫を借りる）
    // sizeof(int) は「int型1個分のサイズ（通常4バイト）」という意味。
    // それを5個分（つまり20バイト）倉庫に確保し、その「先頭の住所」をポインタ p にもらう。
    int *p = (int*)malloc(sizeof(int) * 5);

    // 2. エラーチェック（プロの必須お作法）
    // もしMacのメモリが一杯で倉庫が借りられなかった場合、p には NULL（無効な住所）が入る。
    if (p == NULL) {
        printf("メモリの確保に失敗しました！\n");
        return 1; // エラーとして終了
    }

    // 3. 配列として使う
    // ポインタは、なんとそのまま「配列」のように [ ] を使ってアクセスできる！
    p[0] = 10;
    p[1] = 20;
    p[2] = 30;

    printf("p[0]の中身: %d\n", p[0]);
    printf("p[2]の中身: %d\n", p[2]);

    // 4. メモリの解放（借りた倉庫を返す）★超重要！
    // これを忘れると「メモリリーク（ゴミが残り続ける）」という致命的なバグになる。
    free(p);
    
    printf("メモリを無事に解放しました。\n");

    return 0;
}

// (int*)malloc(sizeof(int) * 5) というのは、
// 「int型（4バイト）を5個分、合計20バイトの広大な倉庫を確保し、そこを『int専用の配列の住所』として使わせろ！」